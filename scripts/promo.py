#!/usr/bin/env python3
"""The MegaBrain promotion every page carries.

Usage:  python3 scripts/promo.py
Writes: an orange bar at the top of every HTML page (it stays in view while
the page scrolls) and a banner at the end of every blog post. Idempotent.
The other generators call apply() when they finish, so a new or regenerated
page gets both without anyone remembering to run this.

To change the wording or the link, edit BAR and BANNER here and run the script;
the colours are in assets/style.css under "MegaBrain promotion".
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
URL = "https://getmegabrain.com/?utm_source=privateslm.dev"

BAR = f"""  <!-- biz-bar:start — generated by scripts/promo.py, do not edit -->
  <a class="biz-bar" href="{URL}" target="_blank" rel="noopener" aria-label="MegaBrain: private AI for your business">
    <span class="biz-tag" aria-hidden="true">For business · MegaBrain</span>
    <span class="biz-long" aria-hidden="true">Private AI for your business</span>
    <span class="biz-short" aria-hidden="true">MegaBrain: private AI for business</span>
    <span class="biz-arrow" aria-hidden="true">→</span>
  </a>
  <!-- biz-bar:end -->"""

BANNER = f"""    <!-- biz-banner:start — generated by scripts/promo.py, do not edit -->
    <a class="biz-banner" href="{URL}" target="_blank" rel="noopener">
      <span class="biz-kicker">For business · MegaBrain</span>
      <span class="biz-title">Private AI for your business</span>
      <span class="biz-text">privateSLM is private AI for one person on one device. For a team or a company there is MegaBrain — a separate product from the same team.</span>
      <span class="biz-cta">Visit MegaBrain →</span>
    </a>
    <!-- biz-banner:end -->"""


def place(text: str, name: str, block: str, before: str = None, after: str = None) -> str:
    """Replace the generated block called `name`, or put it next to an anchor."""
    existing = re.compile(r"[ \t]*<!-- %s:start.*?<!-- %s:end -->" % (name, name), re.S)
    if existing.search(text):
        return existing.sub(lambda _: block, text, count=1)
    if after is not None:
        at = text.index(after) + len(after)
        return text[:at] + "\n" + block + text[at:]
    at = text.rindex(before)
    line = text.rfind("\n", 0, at) + 1
    if not text[line:at].strip():
        at = line  # keep the anchor's own indentation
    return text[:at] + block.rstrip() + "\n" + text[at:]


def apply() -> int:
    changed = 0
    for path in sorted(ROOT.rglob("*.html")):
        if ".git" in path.parts:
            continue
        text = path.read_text(encoding="utf-8")
        new = place(text, "biz-bar", BAR, after="<body>")
        is_post = path.parent.name == "blog" and path.name != "index.html"
        if is_post and "</article>" in new:
            new = place(new, "biz-banner", BANNER, before="</article>")
        if new != text:
            path.write_text(new, encoding="utf-8")
            changed += 1
    return changed


if __name__ == "__main__":
    print(f"promotion written to {apply()} pages")
