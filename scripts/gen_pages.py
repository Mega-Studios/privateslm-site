#!/usr/bin/env python3
"""The generated Omnimo pages: compare, alternatives, models, use cases, prompts,
status explainers, guides, the fact sheet, the translated pages and their .md copies.

Usage:  python3 scripts/gen_pages.py
Writes: every page described in scripts/pagedata/ (HTML, plus a .md copy for the
pages marked `md`), their <url> entries in sitemap.xml, the generated list of pages in
llms.txt (between the `pages:start` / `pages:end` lines), and then runs promo.py so
each page gets the MegaBrain bar and the Smart App Banner. Idempotent.

The words live in scripts/pagedata/*.py; this file only lays them out. Facts about
Omnimo (models, prices, limits, privacy) come from the app repo
(Mega-Studios/omnimo): appstore/metadata/en-US/, docs/monetization.md and
gateway/src/catalog.ts. Facts about other apps come from their own App Store
listings and in-app purchase lists (US storefront), with the date they were read.
When a price or a model changes, change it in pagedata/common.py or
pagedata/competitors.py and run this again.
"""

import html
import json
import re
import sys
from html.parser import HTMLParser
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import promo  # noqa: E402
from pagedata import all_pages  # noqa: E402
from pagedata.common import SITE, UPDATED, APP_STORE, LANGS  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
GENERATED = "<!-- generated by scripts/gen_pages.py from scripts/pagedata/, do not edit -->"


def attr(text: str) -> str:
    return html.escape(html.unescape(text), quote=True)


def plain(fragment: str) -> str:
    """HTML fragment to one line of text (for JSON-LD and meta tags)."""
    text = re.sub(r"<[^>]+>", "", fragment)
    return re.sub(r"\s+", " ", html.unescape(text)).strip()


def url_of(path: str) -> str:
    """Site URL of a page: directories end in /, index.html is dropped."""
    if path == "index.html":
        return f"{SITE}/"
    if path.endswith("/index.html"):
        return f"{SITE}/{path[:-len('index.html')]}"
    return f"{SITE}/{path}"


def href_of(path: str) -> str:
    """Root link to a page: index.html becomes its directory."""
    if path == "index.html":
        return "/"
    if path.endswith("/index.html"):
        return "/" + path[:-len("index.html")]
    return "/" + path


def relative(path: str, body: str) -> str:
    """Turn root links (href="/models/") into links relative to the page."""
    depth = path.count("/")
    up = "../" * depth

    def fix(match):
        target = match.group(2)
        rel = up + target[1:]
        if rel == "":
            rel = "./"
        return f'{match.group(1)}="{rel}'

    return re.sub(r'\b(href|src)="(/(?!/)[^"]*)', fix, body)


def ld(data: dict) -> str:
    return ('  <script type="application/ld+json">'
            + json.dumps(data, ensure_ascii=False).replace("</", "<\\/") + "</script>")


def breadcrumb_ld(crumbs) -> dict:
    return {
        "@context": "https://schema.org", "@type": "BreadcrumbList",
        "itemListElement": [
            {"@type": "ListItem", "position": i, "name": name, "item": url_of(path)}
            for i, (name, path) in enumerate(crumbs, start=1)
        ],
    }


def faq_ld(faq) -> dict:
    return {
        "@context": "https://schema.org", "@type": "FAQPage",
        "mainEntity": [
            {"@type": "Question", "name": plain(q), "acceptedAnswer": {"@type": "Answer", "text": plain(a)}}
            for q, a in faq
        ],
    }


def page_ld(page) -> dict:
    kind = page.get("schema", "Article")
    data = {
        "@context": "https://schema.org", "@type": kind,
        "headline" if kind == "Article" else "name": plain(page["h1"]),
        "description": page["description"],
        "url": url_of(page["path"]),
        "inLanguage": page.get("lang", "en"),
        "dateModified": page.get("updated", UPDATED),
        "image": [f"{SITE}/assets/og-default.png"],
        "publisher": {"@type": "Organization", "name": "Omnimo", "url": f"{SITE}/",
                      "logo": {"@type": "ImageObject", "url": f"{SITE}/assets/favicon.png"}},
    }
    if kind == "Article":
        data["datePublished"] = page.get("published", UPDATED)
        data["author"] = {"@type": "Organization", "name": "Omnimo", "url": f"{SITE}/"}
        data["mainEntityOfPage"] = url_of(page["path"])
    return data


def hreflang_links(page) -> list:
    alts = page.get("alternates")
    if not alts:
        return []
    lines = [f'  <link rel="alternate" hreflang="{code}" href="{url_of(p)}">' for code, p in alts.items()]
    lines.append(f'  <link rel="alternate" hreflang="x-default" href="{url_of(alts["en"])}">')
    return lines


def nav(page) -> str:
    lang = page.get("lang", "en")
    items = LANGS[lang]["nav"]
    links = "\n".join(f'      <a href="{href}">{label}</a>' for label, href in items)
    return f"""  <nav>
    <a class="logo" href="{LANGS[lang]['home']}">Omni<span>mo</span></a>
    <div class="links">
{links}
    </div>
  </nav>"""


def footer(page) -> str:
    lang = page.get("lang", "en")
    items = LANGS[lang]["footer"]
    links = "\n".join(f'    <a href="{href}">{label}</a>' for label, href in items)
    langs = ""
    if page.get("alternates"):
        others = [f'<a href="{href_of(p)}" hreflang="{code}" lang="{code}">{LANGS[code]["name"]}</a>'
                  for code, p in page["alternates"].items() if code != lang]
        langs = '\n    <span class="langs">' + " · ".join(others) + "</span>"
    return f"""  <footer>
    <span>© 2026 Omnimo</span>{langs}
    <span class="spacer"></span>
{links}
  </footer>"""


def faq_html(page) -> str:
    if not page.get("faq"):
        return ""
    heading = LANGS[page.get("lang", "en")]["faq"]
    parts = [f"\n    <h2>{heading}</h2>"]
    for q, a in page["faq"]:
        parts.append(f"    <h3>{q}</h3>\n    <p>{a}</p>")
    return "\n".join(parts)


def render(page) -> str:
    lang = page.get("lang", "en")
    canonical = url_of(page["path"])
    title = page["title"]
    og_title = page.get("og_title", plain(page["h1"]))
    lds = [page_ld(page)]
    if page.get("crumbs"):
        lds.append(breadcrumb_ld(page["crumbs"]))
    if page.get("faq"):
        lds.append(faq_ld(page["faq"]))
    lds.extend(page.get("extra_ld", []))
    md_link = []
    if page.get("md"):
        md_link = [f'  <link rel="alternate" type="text/markdown" href="{md_url(page["path"])}">']
    head = [
        "<!DOCTYPE html>",
        f'<html lang="{LANGS[lang]["code"]}">',
        "<head>",
        '  <meta charset="UTF-8">',
        '  <meta name="viewport" content="width=device-width, initial-scale=1.0">',
        '  <meta name="apple-itunes-app" content="app-id=6504996891">',
        f"  <title>{html.escape(title, quote=False)}</title>",
        f'  <meta name="description" content="{attr(page["description"])}">',
        '  <link rel="stylesheet" href="/assets/style.css">',
        '  <link rel="icon" href="/assets/favicon.png">',
        f'  <link rel="canonical" href="{canonical}">',
        *hreflang_links(page),
        *md_link,
        f"  {GENERATED}",
        f'  <meta property="og:type" content="{page.get("og_type", "article")}">',
        '  <meta property="og:site_name" content="Omnimo">',
        f'  <meta property="og:title" content="{attr(og_title)}">',
        f'  <meta property="og:description" content="{attr(page["description"])}">',
        f'  <meta property="og:url" content="{canonical}">',
        f'  <meta property="og:image" content="{SITE}/assets/og-default.png">',
        f'  <meta property="og:locale" content="{LANGS[lang]["og"]}">',
        '  <meta name="twitter:card" content="summary_large_image">',
        *[ld(d) for d in lds],
        "</head>",
        "<body>",
    ]
    crumbs = ""
    if page.get("crumbs") and len(page["crumbs"]) > 1:
        trail = " / ".join(f'<a href="{href_of(p)}">{n}</a>' for n, p in page["crumbs"][:-1])
        crumbs = f'\n    <div class="crumbs">{trail}</div>'
    if page.get("raw"):
        body = page["raw"]
    else:
        cta = page.get("cta", True)
        cta_html = ""
        if cta:
            label = LANGS[lang]["cta"]
            cta_html = f'\n    <div class="cta"><a class="btn solid" href="{APP_STORE}">{label}</a></div>'
        fine = page.get("fine", LANGS[lang]["fine"])
        body = f"""{nav(page)}
  <div class="page">
    <div class="wrap">
<article>{crumbs}
    <h1>{page['h1']}</h1>
    <div class="meta">{page['meta']}</div>
{page['body'].strip(chr(10))}
{faq_html(page)}{cta_html}
    <p class="fine">{fine}</p>
</article>
    </div>
  </div>
{footer(page)}"""
    text = "\n".join(head) + "\n" + body + "\n</body>\n</html>\n"
    return relative(page["path"], text)


# ---------- Markdown copies ----------

def md_url(path: str) -> str:
    if path == "index.html":
        return f"{SITE}/index.md"
    if path.endswith("/index.html"):
        return f"{SITE}/{path[:-len('.html')]}.md"
    return f"{SITE}/{path[:-len('.html')]}.md"


def md_path(path: str) -> str:
    return path[:-len(".html")] + ".md"


class ToMarkdown(HTMLParser):
    """Enough HTML to Markdown for these pages: headings, paragraphs, lists,
    tables, links, emphasis, code and pre."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.out, self.buf = [], []
        self.href = []
        self.lists = []
        self.row, self.rows, self.cell = None, None, None
        self.pre = False
        self.skip = 0

    def flush(self):
        text = "".join(self.buf)
        self.buf = []
        if not self.pre:
            text = re.sub(r"[ \t\n]+", " ", text).strip()
        return text

    def emit(self, text):
        if text:
            self.out.append(text)

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag in ("script", "style", "button", "nav", "footer"):
            self.skip += 1
            return
        if self.skip:
            return
        if tag in ("h1", "h2", "h3", "p", "li", "blockquote", "div") and self.cell is None:
            self.emit(self.flush())
        if tag == "a":
            self.href.append(a.get("href", ""))
            self.buf.append("[")
        elif tag in ("strong", "b"):
            self.buf.append("**")
        elif tag in ("em", "i"):
            self.buf.append("*")
        elif tag == "code" and not self.pre:
            self.buf.append("`")
        elif tag == "pre":
            self.emit(self.flush())
            self.pre = True
        elif tag == "br":
            self.buf.append("  \n" if self.cell is None else " ")
        elif tag in ("ul", "ol"):
            self.lists.append([tag, 0])
        elif tag == "table":
            self.rows = []
        elif tag == "tr":
            self.row = []
        elif tag in ("td", "th"):
            self.flush_cell_start()

    def flush_cell_start(self):
        self.buf = []
        self.cell = True

    def handle_endtag(self, tag):
        if tag in ("script", "style", "button", "nav", "footer"):
            self.skip -= 1
            return
        if self.skip:
            return
        if tag == "a":
            href = self.href.pop() if self.href else ""
            if href.startswith("/"):
                href = SITE + href
            self.buf.append(f"]({href})")
        elif tag in ("strong", "b"):
            self.buf.append("**")
        elif tag in ("em", "i"):
            self.buf.append("*")
        elif tag == "code" and not self.pre:
            self.buf.append("`")
        elif tag == "pre":
            code = "".join(self.buf).strip("\n")
            self.buf = []
            self.pre = False
            self.emit("```\n" + code + "\n```")
        elif tag in ("h1", "h2", "h3"):
            self.emit("#" * int(tag[1]) + " " + self.flush())
        elif tag in ("p", "div", "blockquote"):
            text = self.flush()
            if text and tag == "blockquote":
                text = "> " + text
            self.emit(text)
        elif tag == "li":
            kind = self.lists[-1] if self.lists else ["ul", 0]
            kind[1] += 1
            mark = f"{kind[1]}." if kind[0] == "ol" else "-"
            text = self.flush()
            if text:
                self.out.append(f"{mark} {text}")
        elif tag in ("ul", "ol"):
            self.emit(self.flush())
            if self.lists:
                self.lists.pop()
        elif tag in ("td", "th"):
            self.row.append(self.flush().replace("|", "\\|"))
            self.cell = None
        elif tag == "tr":
            self.rows.append(self.row)
            self.row = None
        elif tag == "table":
            rows = self.rows or []
            self.rows = None
            if rows:
                width = max(len(r) for r in rows)
                rows = [r + [""] * (width - len(r)) for r in rows]
                lines = ["| " + " | ".join(rows[0]) + " |", "|" + " --- |" * width]
                lines += ["| " + " | ".join(r) + " |" for r in rows[1:]]
                self.out.append("\n".join(lines))

    def handle_data(self, data):
        if not self.skip:
            self.buf.append(data)


def to_markdown(page, rendered: str) -> str:
    article = re.search(r"<article>(.*)</article>", rendered, re.S)
    fragment = article.group(1) if article else rendered
    fragment = re.sub(r'<div class="crumbs">.*?</div>', "", fragment, flags=re.S)
    fragment = re.sub(r"<!-- biz-banner:start.*?biz-banner:end -->", "", fragment, flags=re.S)
    # links in the rendered page are relative; make them absolute again
    base = url_of(page["path"])
    base = base if base.endswith("/") else base.rsplit("/", 1)[0] + "/"

    def absolute(m):
        href = m.group(1)
        if re.match(r"^(https?:|mailto:|#)", href):
            return f'href="{href}"'
        from urllib.parse import urljoin
        return f'href="{urljoin(base, href)}"'

    fragment = re.sub(r'href="([^"]*)"', absolute, fragment)
    parser = ToMarkdown()
    parser.feed(fragment)
    parser.emit(parser.flush())
    body = "\n\n".join(x for x in parser.out if x.strip())
    head = (f"<!-- Markdown copy of {url_of(page['path'])} for assistants and LLMs. "
            f"Generated by scripts/gen_pages.py. -->\n\n")
    return head + body + f"\n\nSource: {url_of(page['path'])}\n"


# ---------- sitemap and llms.txt ----------

def update_sitemap(pages) -> int:
    path = ROOT / "sitemap.xml"
    text = path.read_text(encoding="utf-8")
    changed = 0
    for page in pages:
        loc = url_of(page["path"])
        mod = page.get("updated", UPDATED)
        entry = re.search(r"  <url>\n    <loc>" + re.escape(loc) + r"</loc>\n    <lastmod>(.*?)</lastmod>\n  </url>\n", text)
        fresh = f"  <url>\n    <loc>{loc}</loc>\n    <lastmod>{mod}</lastmod>\n  </url>\n"
        if entry is None:
            text = text.replace("</urlset>", fresh + "</urlset>")
            changed += 1
        elif entry.group(1) < mod:
            text = text.replace(entry.group(0), fresh)
            changed += 1
    path.write_text(text, encoding="utf-8")
    return changed


LLMS_START = "<!-- pages:start — generated by scripts/gen_pages.py, do not edit -->"
LLMS_END = "<!-- pages:end -->"


def update_llms(pages, extra_md) -> None:
    path = ROOT / "llms.txt"
    text = path.read_text(encoding="utf-8")
    sections = {}
    for page in pages:
        if page.get("lang", "en") != "en" or not page.get("llms"):
            continue
        sections.setdefault(page["llms"], []).append(page)
    order = ["Facts", "Compare", "Alternatives", "Models", "Use cases", "Guides", "Status explainers", "Prompt library"]
    lines = [LLMS_START]
    for name in order:
        if name not in sections:
            continue
        lines.append(f"\n## {name}\n")
        for page in sections[name]:
            line = f"- {plain(page['h1'])}: {url_of(page['path'])}"
            if page.get("md"):
                line += f" (Markdown: {md_url(page['path'])})"
            lines.append(line)
    lines.append("\n## Other languages\n")
    for code in ("es", "de", "fr", "pt-BR", "ja"):
        lines.append(f"- {LANGS[code]['name']}: {SITE}/{LANGS[code]['dir']}/")
    lines.append("\n## Markdown copies\n")
    lines.append("Every page marked (Markdown) above has a plain-text copy at the same address with .md for .html. Also:")
    for label, url in extra_md:
        lines.append(f"- {label}: {url}")
    lines.append(LLMS_END)
    block = "\n".join(lines)
    if LLMS_START in text:
        text = re.sub(re.escape(LLMS_START) + r".*?" + re.escape(LLMS_END), lambda _: block, text, flags=re.S)
    else:
        anchor = "## Archive: privateSLM before Omnimo"
        text = text.replace(anchor, block + "\n\n" + anchor)
    path.write_text(text, encoding="utf-8")


def main():
    pages = all_pages()
    paths = [p["path"] for p in pages]
    dupes = {p for p in paths if paths.count(p) > 1}
    if dupes:
        sys.exit(f"duplicate pages: {sorted(dupes)}")
    written = 0
    for page in pages:
        out = ROOT / page["path"]
        out.parent.mkdir(parents=True, exist_ok=True)
        rendered = render(page)
        # what promo.apply() will leave in the file, so an unchanged page is not rewritten
        rendered = promo.place(rendered, "biz-bar", promo.BAR, after="<body>")
        if not out.exists() or out.read_text(encoding="utf-8") != rendered:
            out.write_text(rendered, encoding="utf-8")
            written += 1
        if page.get("md"):
            (ROOT / md_path(page["path"])).write_text(to_markdown(page, rendered), encoding="utf-8")
    # Markdown copies of two hand-written pages: the home page and the rename post.
    extra = []
    for src, label in (("index.html", "Home page"), ("blog/privateslm-is-now-omnimo.html", "privateSLM is now Omnimo")):
        page = {"path": src}
        text = (ROOT / src).read_text(encoding="utf-8")
        if src == "index.html":
            text = "<article>" + re.sub(r"(?s).*?<section class=\"panel hero\">", "", text)
            text = re.sub(r'(?s)<section class="panel biz".*', "", text) + "</article>"
            text = re.sub(r'<a class="rename-note".*?</a>', "", text, flags=re.S)
            text = re.sub(r'<div class="(kicker|stats|stat|num|label)">', "<div>", text)
        (ROOT / md_path(src)).write_text(to_markdown(page, text), encoding="utf-8")
        extra.append((label, md_url(src)))
    added = update_sitemap(pages)
    update_llms(pages, extra)
    md = sum(1 for p in pages if p.get("md")) + len(extra)
    print(f"{len(pages)} pages ({written} written), {md} Markdown copies, {added} sitemap entries added or refreshed")
    print(f"promotion and Smart App Banner written to {promo.apply()} pages")


if __name__ == "__main__":
    main()
