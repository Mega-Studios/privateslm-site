#!/usr/bin/env python3
"""Give every blog post the tags search engines and link previews read.

Usage:  python3 scripts/gen_blog_meta.py
Writes: a generated block in the <head> of each blog/*.html (Open Graph,
Twitter card, BlogPosting structured data) and one <url> per post in
sitemap.xml. Idempotent — run it after adding or editing a post.

Everything is derived from the post itself: the <title>, the meta
description, the canonical link, the date in <div class="meta">, and the
first image in the article (posts without one get assets/og-default.png).
To mark a post as revised, put the date in the meta line as
"Updated October 11, 2026"; it becomes dateModified and the sitemap's lastmod.
"""

import html
import json
import re
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = "https://www.privateslm.dev"
DEFAULT_IMAGE = f"{SITE}/assets/og-default.png"
START = "  <!-- seo:start — generated by scripts/gen_blog_meta.py, do not edit -->"
END = "  <!-- seo:end -->"

MONTHS = {m: i for i, m in enumerate(
    ["January", "February", "March", "April", "May", "June", "July", "August",
     "September", "October", "November", "December"], start=1)}
DATE = re.compile(r"(%s) (\d{1,2}), (\d{4})" % "|".join(MONTHS))


def iso(match) -> str:
    return date(int(match.group(3)), MONTHS[match.group(1)], int(match.group(2))).isoformat()


def attr(text: str) -> str:
    """Escape for an HTML attribute value."""
    return html.escape(html.unescape(text), quote=True)


def read_post(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")

    def need(pattern, what):
        found = re.search(pattern, text, re.S)
        if not found:
            sys.exit(f"{path.relative_to(ROOT)}: no {what}")
        return found.group(1).strip()

    title = need(r"<title>(.*?)</title>", "<title>")
    title = re.sub(r"\s+[—-]\s+privateSLM blog$", "", html.unescape(title))
    description = html.unescape(need(r'<meta name="description" content="(.*?)">', "meta description"))
    canonical = need(r'<link rel="canonical" href="(.*?)">', "canonical link")
    meta_line = need(r'<div class="meta">(.*?)</div>', 'date line (<div class="meta">)')

    published = DATE.search(meta_line)
    if not published:
        sys.exit(f"{path.relative_to(ROOT)}: no date in the meta line: {meta_line!r}")
    updated = re.search(r"Updated[: ]+" + DATE.pattern, meta_line)
    image = re.search(r'<img[^>]+src="\.\./(assets/[^"]+)"', text)

    return {
        "path": path, "text": text, "title": title, "description": description,
        "canonical": canonical, "published": iso(published),
        "modified": iso(re.search(DATE.pattern, updated.group(0))) if updated else iso(published),
        "image": f"{SITE}/{image.group(1)}" if image else DEFAULT_IMAGE,
    }


def head_block(post: dict) -> str:
    structured = {
        "@context": "https://schema.org",
        "@type": "BlogPosting",
        "headline": post["title"],
        "description": post["description"],
        "datePublished": post["published"],
        "dateModified": post["modified"],
        "image": [post["image"]],
        "mainEntityOfPage": post["canonical"],
        "author": {"@type": "Organization", "name": "privateSLM", "url": f"{SITE}/"},
        "publisher": {
            "@type": "Organization", "name": "privateSLM",
            "logo": {"@type": "ImageObject", "url": f"{SITE}/assets/favicon.png"},
        },
    }
    lines = [
        START,
        '  <meta property="og:type" content="article">',
        '  <meta property="og:site_name" content="privateSLM">',
        f'  <meta property="og:title" content="{attr(post["title"])}">',
        f'  <meta property="og:description" content="{attr(post["description"])}">',
        f'  <meta property="og:url" content="{attr(post["canonical"])}">',
        f'  <meta property="og:image" content="{attr(post["image"])}">',
        f'  <meta property="article:published_time" content="{post["published"]}">',
        f'  <meta property="article:modified_time" content="{post["modified"]}">',
        '  <meta name="twitter:card" content="summary_large_image">',
        # "</" must not appear inside a script element.
        '  <script type="application/ld+json">'
        + json.dumps(structured, ensure_ascii=False).replace("</", "<\\/") + "</script>",
        END,
    ]
    return "\n".join(lines)


def write_head(post: dict) -> bool:
    text, block = post["text"], head_block(post)
    if START in text:
        new = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    else:
        canonical = re.search(r'^.*<link rel="canonical".*$', text, re.M)
        new = text[:canonical.end()] + "\n" + block + text[canonical.end():]
    if new == text:
        return False
    post["path"].write_text(new, encoding="utf-8")
    return True


def update_sitemap(posts: list) -> int:
    path = ROOT / "sitemap.xml"
    text = path.read_text(encoding="utf-8")
    changed = 0
    for post in sorted(posts, key=lambda p: (p["published"], p["canonical"])):
        entry = re.search(
            r"  <url>\n    <loc>" + re.escape(post["canonical"]) + r"</loc>\n    <lastmod>(.*?)</lastmod>\n  </url>\n",
            text)
        fresh = f"  <url>\n    <loc>{post['canonical']}</loc>\n    <lastmod>{post['modified']}</lastmod>\n  </url>\n"
        if entry is None:
            text = text.replace("</urlset>", fresh + "</urlset>")
            changed += 1
        elif entry.group(1) < post["modified"]:
            text = text.replace(entry.group(0), fresh)
            changed += 1
    path.write_text(text, encoding="utf-8")
    return changed


def main():
    posts = [read_post(p) for p in sorted((ROOT / "blog").glob("*.html")) if p.name != "index.html"]
    heads = sum(write_head(p) for p in posts)
    urls = update_sitemap(posts)
    print(f"{len(posts)} posts: {heads} heads written, {urls} sitemap entries added or refreshed")


if __name__ == "__main__":
    main()
